import { Award, CalendarCheck, Download, Printer } from "lucide-react";
import { getAverage, getGrade, resultStudents } from "@/lib/results-center";

export function ReportCardPreview({ student = resultStudents[0] }: { student?: typeof resultStudents[number] }) {
  const average = getAverage(student.subjects);
  const grade = getGrade(average);

  return (
    <div className="report-card-shell">
      <div className="report-card-actions"><button className="btn btn-primary" type="button"><Printer size={18} /> Print</button><button className="btn btn-secondary" type="button"><Download size={18} /> Download PDF</button></div>
      <article className="report-card">
        <header>
          <div className="report-logo"><Award /></div>
          <div><h1>Greenfield International School</h1><p>Premium Academic Report Card • {student.term} • {student.session}</p></div>
          <span className="status good">{student.status}</span>
        </header>
        <section className="report-student-grid">
          <div><span>Student</span><strong>{student.name}</strong></div>
          <div><span>Admission No.</span><strong>{student.id}</strong></div>
          <div><span>Class</span><strong>{student.className}</strong></div>
          <div><span>Position</span><strong>{student.position}</strong></div>
          <div><span>Attendance</span><strong>{student.attendance}%</strong></div>
          <div><span>Average</span><strong>{average}% • {grade.grade}</strong></div>
        </section>
        <table className="report-table"><thead><tr><th>Subject</th><th>CA</th><th>Exam</th><th>Total</th><th>Grade</th><th>Remark</th></tr></thead><tbody>{student.subjects.map((subject) => { const subjectGrade = getGrade(subject.total); return <tr key={subject.name}><td>{subject.name}</td><td>{subject.ca}</td><td>{subject.exam}</td><td>{subject.total}</td><td>{subjectGrade.grade}</td><td>{subjectGrade.remark}</td></tr>; })}</tbody></table>
        <section className="report-comments"><div><strong>Class Teacher Comment</strong><p>{student.teacherComment}</p></div><div><strong>Principal Comment</strong><p>{student.principalComment}</p></div></section>
        <footer><span><CalendarCheck size={15} /> Attendance verified</span><span>Generated by EduManage School OS</span></footer>
      </article>
    </div>
  );
}
